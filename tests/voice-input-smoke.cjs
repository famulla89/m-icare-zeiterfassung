'use strict';
const assert=require('node:assert/strict');
const v=require('../voice-input.js');
assert.equal(v.postal('fünf acht null neun sieben'),'58097');
assert.equal(v.postal('5 8 0 9 7'),'58097');
assert.equal(v.postal('PLZ fünf acht null neun sieben'),'58097');
assert.equal(v.postal('null eins zwei drei vier'),'01234','Preserve leading zeros');
assert.equal(v.postal('58097'),'58097');
for(const invalid of ['fünf acht neun sieben','fünf acht null neun sieben acht','acht gelb null vier fünf','', 'PLZ'])assert.equal(v.postal(invalid),null,'Reject ambiguous/malformed post code: '+invalid);
assert.equal(v.houseNumber('zwölf a'),'12a');
assert.equal(v.houseNumber('12 A'),'12a');
assert.equal(v.houseNumber('Hausnummer neun'),'9');
assert.equal(v.houseNumber('12 bis 14'),null,'Do not guess street number ranges');
assert.equal(v.houseNumber('12-14'),'12-14');
assert.equal(v.houseNumber('zwölf'), '12');
assert.equal(v.houseNumber(''), '');
assert.equal(v.houseNumber('Lippestraße'),null);
assert.equal(v.phone('null eins sieben sechs zwei drei'),'017623');
assert.equal(v.phone('plus vier neun eins fünf zwei'),'+49152');
assert.equal(v.phone('unverständlich'),null);
assert.deepEqual(v.splitAddress('Lippestraße 9a'),{street:'Lippestraße',houseNumber:'9a'});
assert.deepEqual(v.splitAddress('Am Markt 12-14'),{street:'Am Markt',houseNumber:'12-14'});
assert.deepEqual(v.splitAddress('Straße des 17. Juni 112'),{street:'Straße des 17. Juni',houseNumber:'112'});
assert.deepEqual(v.splitAddress('Unvollständige Adresse'),{street:'Unvollständige Adresse',houseNumber:''});
assert.equal(v.address('Lippestraße','9a'),'Lippestraße 9a');
assert.equal(v.address('Kaiserstraße',''),'Kaiserstraße');
console.log('VOICE/ADDRESS PASS: spoken five-digit PLZ including leading zero, house number, phone, legacy address split and recomposition');